import { readFile, stat } from 'node:fs/promises';
import { dirname, join, posix, relative } from 'node:path';
import { isOperationName, normalizeParams, registryHash, REGISTRY_FORMAT_VERSION, type OperationParam } from '../registry';
import type { SurfaceOperation } from './internal/client';
import { parseRegistrySource } from './registry-source';

/**
 * The deterministic generator behind `faustine-next init` (and `sync`, I3):
 * surface map + the app's layout in, three files out. Pure functions over
 * strings so they are testable without a filesystem; `readLayout` is the one
 * piece that looks at the disk.
 */

export interface AppLayout {
  /** Where `app/` lives relative to the project root: `app` or `src/app`. */
  appDir: string;
  /** `src` when the app lives under src/, else ''. */
  srcRoot: string;
  /** The import alias that maps to the source root (`@/`), when tsconfig declares one. */
  alias: string | null;
  /** The registry file, relative to the project root. */
  registryFile: string;
  /** The route handler file, relative to the project root. */
  routeFile: string;
  /** `AGENTS.md` at the project root. */
  agentsFile: string;
}

async function exists(p: string): Promise<boolean> {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

/** Reads the project layout: `app/` vs `src/app/`, the `@/` alias from tsconfig. */
export async function readLayout(root: string): Promise<AppLayout> {
  const src = await exists(join(root, 'src', 'app'));
  if (!src && !(await exists(join(root, 'app')))) {
    throw new Error('No `app/` or `src/app/` directory here — faustine-next supports the Next.js App Router. Run it from the Next.js project root.');
  }
  const srcRoot = src ? 'src' : '';
  let alias: string | null = null;
  try {
    const raw = await readFile(join(root, 'tsconfig.json'), 'utf-8');
    const paths = (parseTsconfig(raw) as { compilerOptions?: { paths?: Record<string, string[]> } }).compilerOptions?.paths ?? {};
    for (const [key, targets] of Object.entries(paths)) {
      const target = targets[0] ?? '';
      const expected = srcRoot ? './src/*' : './*';
      if (key.endsWith('/*') && (target === expected || target === expected.replace('./', ''))) {
        alias = key.slice(0, -1); // "@/*" → "@/"
        break;
      }
    }
  } catch {
    // no tsconfig or unreadable: relative imports
  }
  return layoutFor(srcRoot, alias);
}

export function layoutFor(srcRoot: '' | 'src', alias: string | null): AppLayout {
  const base = srcRoot ? `${srcRoot}/` : '';
  return {
    appDir: `${base}app`,
    srcRoot,
    alias,
    registryFile: `${base}faustine/registry.ts`,
    routeFile: `${base}app/api/faustine/[...op]/route.ts`,
    agentsFile: 'AGENTS.md',
  };
}

/** tsconfig is JSON with comments and trailing commas; `"@/*"` contains `/*`, so never strip block comments blindly. */
export function parseTsconfig(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    const relaxed = raw.replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[}\]])/g, '$1');
    return JSON.parse(relaxed);
  }
}

/** The import specifier for a source file, from a file in the project: alias when there is one, relative otherwise. */
export function importPathFor(file: string, fromFile: string, layout: AppLayout): string {
  const noExt = file.replace(/\.(tsx?|jsx?|mjs|cjs)$/, '');
  const base = layout.srcRoot ? `${layout.srcRoot}/` : '';
  if (layout.alias && noExt.startsWith(base)) return `${layout.alias}${noExt.slice(base.length)}`;
  let rel = posix.relative(posix.dirname(fromFile), noExt);
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

export interface RegistryPlan {
  webAgent: string;
  operations: { operation: string; file: string; symbol: string; description: string; params?: OperationParam[] | null }[];
}

/** `params: ['id', { name: 'formData', kind: 'formData' }]` as the registry line writes it. */
export function renderParams(params: OperationParam[]): string {
  const items = params.map((p) => (typeof p === 'string' ? `'${p}'` : `{ name: '${p.name}', kind: '${p.kind ?? 'value'}' }`));
  return `[${items.join(', ')}]`;
}

/** `faustine/registry.ts` — generated, committed, reviewed. */
export function renderRegistry(plan: RegistryPlan, layout: AppLayout): string {
  const lines = plan.operations
    .slice()
    .sort((a, b) => a.operation.localeCompare(b.operation))
    .map((op) => {
      const spec = importPathFor(op.file, layout.registryFile, layout);
      const params = op.params ? `, params: ${renderParams(op.params)}` : '';
      return `  // ${op.description}\n  '${op.operation}': { fn: () => import('${spec}').then((m) => m.${op.symbol})${params} },`;
    });
  return `// faustine/registry.ts — GENERATED by \`npx faustine-next init\`. Commit it.
// What the Faustine Web Agent may call in this app: one line per operation,
// a name Faustine knows and an import of the real function. Remove a line to
// stop exposing that operation; run \`npx faustine-next sync\` after adding
// Server Actions or data functions. Names are Faustine's, bindings are yours.
// \`params\` is the function's parameter list, read from its signature: how the
// agent's input becomes the call (one value → the input itself; several → an
// object keyed by name; a FormData parameter is built from the input's fields;
// a useActionState \`prevState\` is never sent).
import { createRegistry } from '@faustine-ai/next'

export default createRegistry({ webAgent: '${plan.webAgent}', formatVersion: ${REGISTRY_FORMAT_VERSION} }, {
${lines.join('\n')}
})
`;
}

/** `app/api/faustine/[...op]/route.ts` — three lines. */
export function renderRouteHandler(layout: AppLayout): string {
  const spec = importPathFor(layout.registryFile, layout.routeFile, layout);
  return `import { createFaustineHandler } from '@faustine-ai/next'
import registry from '${spec}'

export const { GET, POST } = createFaustineHandler(registry)
`;
}

export const AGENTS_BEGIN = '<!-- BEGIN:faustine -->';
export const AGENTS_END = '<!-- END:faustine -->';

export function renderAgentsBlock(layout: AppLayout): string {
  return `${AGENTS_BEGIN}
## Faustine Web Agent

This app exposes server functions to its Faustine Web Agent through
\`${layout.registryFile}\` (generated) and the route handler at
\`${layout.routeFile}\`. Keep them in step with the code:

- After adding, renaming or removing a Server Action or a data-layer function
  the agent should reach, run \`npx faustine-next sync\` and review the diff of
  the registry. Never edit the registry's operation names by hand — they are
  the names the agent knows.
- Removing a line from the registry stops exposing that operation; that is
  the intended way to keep something private.
- \`npx faustine-next doctor\` compares the running app with what Faustine
  expects; run it after a deploy that touched the registry.
${AGENTS_END}`;
}

/** Inserts or replaces the Faustine block in an existing AGENTS.md (or creates the file's content). */
export function upsertAgentsBlock(existing: string | null, block: string): string {
  if (existing == null || existing.trim() === '') return `# Agent instructions\n\n${block}\n`;
  const start = existing.indexOf(AGENTS_BEGIN);
  const end = existing.indexOf(AGENTS_END);
  if (start !== -1 && end !== -1 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + AGENTS_END.length);
  }
  return existing.replace(/\s*$/, '') + `\n\n${block}\n`;
}

/** The hash the runtime will compute for the registry this plan renders. */
export function planHash(plan: RegistryPlan): string {
  return registryHash(
    { webAgent: plan.webAgent, formatVersion: REGISTRY_FORMAT_VERSION },
    plan.operations.map((o) => ({ name: o.operation, schema: false, confirm: false, params: normalizeParams(o.params ?? undefined) })),
  );
}

/** Reads the Web Agent id out of an existing registry file (so `init` / `sync` need no flag). */
export function webAgentOfRegistry(source: string): string | null {
  return parseRegistrySource(source).webAgent;
}

/** The operation names an existing registry binds — what `sync` keeps by default (a removed line stays removed). */
export function operationsOfRegistry(source: string): string[] {
  return parseRegistrySource(source).entries.map((e) => e.operation);
}

/** Which operations of the surface map the generator binds: the adapter kinds with a valid name and a symbol. */
export function bindableOperations(ops: SurfaceOperation[], only?: string[] | null): SurfaceOperation[] {
  const wanted = only && only.length > 0 ? new Set(only) : null;
  return ops.filter(
    (o) =>
      (o.kind === 'server-action' || o.kind === 'data-layer') &&
      isOperationName(o.operation) &&
      /^[A-Za-z_$][\w$]*$/.test(o.symbol) &&
      (!wanted || wanted.has(o.operation)),
  );
}

export function fileExistsSync(root: string, rel: string): Promise<boolean> {
  return exists(join(root, rel));
}

export function dirOf(root: string, rel: string): string {
  return dirname(join(root, rel));
}

export function relFrom(root: string, abs: string): string {
  return relative(root, abs);
}
